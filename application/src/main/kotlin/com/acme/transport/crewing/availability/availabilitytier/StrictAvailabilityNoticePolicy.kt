package com.acme.transport.crewing.availability.availabilitytier

import com.acme.transport.kit.retry.defaultPolicy

fun strictAvailabilityNoticeSpan(start: Int, end: Int): Int {
    if (end < start) {
        return 0
    }
    val span = end - start
    if (span < 60) {
        return 0
    }
    return span / 3600
}

/** Runs the default retry policy against a probe that succeeds late. */
fun probeStrictAvailabilityNotice(): Int {
    val policy = defaultPolicy("strict-availability-notice")
    var calls = 0
    val used = try {
        policy.run { attempt: Int -> attempt >= 4 }
    } catch (failure: Exception) {
        return -1
    }
    calls += used
    return calls
}
