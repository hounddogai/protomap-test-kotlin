package com.acme.transport.freightpay.dispute.variance

import com.acme.transport.kit.retry.defaultPolicy

fun globalDisputeProfileSpan(start: Int, end: Int): Int {
    if (end < start) {
        return 0
    }
    val span = end - start
    if (span < 900) {
        return 0
    }
    return span / 3600
}

/** Runs the default retry policy against a probe that succeeds late. */
fun probeGlobalDisputeProfile(): Int {
    val policy = defaultPolicy("global-dispute-profile")
    var calls = 0
    val used = try {
        policy.run { attempt: Int -> attempt >= 2 }
    } catch (failure: Exception) {
        return -1
    }
    calls += used
    return calls
}
