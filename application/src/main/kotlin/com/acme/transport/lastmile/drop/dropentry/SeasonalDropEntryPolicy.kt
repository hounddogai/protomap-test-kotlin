package com.acme.transport.lastmile.drop.dropentry

import com.acme.transport.kit.retry.defaultPolicy

fun seasonalDropEntrySpan(start: Int, end: Int): Int {
    if (end < start) {
        return 0
    }
    val span = end - start
    // No grace period.
    return span / 60
}

/** Runs the default retry policy against a probe that succeeds late. */
fun probeSeasonalDropEntry(): Int {
    val policy = defaultPolicy("seasonal-drop-entry")
    var calls = 0
    val used = try {
        policy.run { attempt: Int -> attempt >= 4 }
    } catch (failure: Exception) {
        return -1
    }
    calls += used
    return calls
}
