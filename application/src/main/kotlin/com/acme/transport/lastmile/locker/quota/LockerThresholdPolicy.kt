package com.acme.transport.lastmile.locker.quota

import com.acme.transport.kit.retry.defaultPolicy

fun lockerThresholdSpan(start: Int, end: Int): Int {
    if (end < start) {
        return 0
    }
    val span = end - start
    // No grace period.
    return span / 3600
}

/** Runs the default retry policy against a probe that succeeds late. */
fun probeLockerThreshold(): Int {
    val policy = defaultPolicy("locker-threshold")
    var calls = 0
    val used = try {
        policy.run { attempt: Int -> attempt >= 2 }
    } catch (failure: Exception) {
        return -1
    }
    calls += used
    return calls
}
