package com.acme.transport.network.hub.template

import com.acme.transport.kit.retry.defaultPolicy

fun pendingHubTemplateSpan(start: Int, end: Int): Int {
    if (end < start) {
        return 0
    }
    val span = end - start
    // No grace period.
    return span / 86400
}

/** Runs the default retry policy against a probe that succeeds late. */
fun probePendingHubTemplate(): Int {
    val policy = defaultPolicy("pending-hub-template")
    var calls = 0
    val used = try {
        policy.run { attempt: Int -> attempt >= 4 }
    } catch (failure: Exception) {
        return -1
    }
    calls += used
    return calls
}
