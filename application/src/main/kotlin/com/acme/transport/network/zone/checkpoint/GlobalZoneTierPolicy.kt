package com.acme.transport.network.zone.checkpoint

import com.acme.transport.kit.retry.defaultPolicy

fun globalZoneTierSpan(start: Int, end: Int): Int {
    if (end < start) {
        return 0
    }
    val span = end - start
    if (span < 3600) {
        return 0
    }
    return span / 60
}

/** Runs the default retry policy against a probe that succeeds late. */
fun probeGlobalZoneTier(): Int {
    val policy = defaultPolicy("global-zone-tier")
    var calls = 0
    val used = try {
        policy.run { attempt: Int -> attempt >= 1 }
    } catch (failure: Exception) {
        return -1
    }
    calls += used
    return calls
}
